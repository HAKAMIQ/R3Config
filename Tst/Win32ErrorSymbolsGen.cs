using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

// Development-only generator of Core/Svc/Log/Win32ErrorSymbols.g.cs from the
// Windows SDK winerror.h (primary source, "#define ERROR_x <number>" facts only).
// Deterministic (sorted by code, aliases in header order). Never runs in the product.
//
//   R3Test.exe --gen-win32-symbols <winerror.h> <out.g.cs>
internal static partial class Win32ErrorSymbolsGen
{
    [GeneratedRegex(@"^#define\s+(?<name>ERROR_[A-Z0-9_]+)\s+(?<value>\d+)L?\s*(?://.*)?$", RegexOptions.CultureInvariant)]
    private static partial Regex DefineRegex();

    public static void Run(string headerPath, string outPath)
    {
        var symbols = new SortedDictionary<int, List<string>>();
        foreach (var line in File.ReadLines(headerPath))
        {
            var match = DefineRegex().Match(line.Trim());
            if (!match.Success ||
                !int.TryParse(match.Groups["value"].Value, NumberStyles.None, CultureInfo.InvariantCulture, out var code) ||
                code is < 0 or >= 16000)
            {
                continue;
            }

            if (!symbols.TryGetValue(code, out var list))
            {
                symbols[code] = list = [];
            }

            if (!list.Contains(match.Groups["name"].Value))
            {
                list.Add(match.Groups["name"].Value);
            }
        }

        var text = new StringBuilder();
        text.Append("// <auto-generated>\n");
        text.Append("// Generated by R3Test --gen-win32-symbols from the Windows SDK winerror.h (");
        text.Append(Path.GetFileName(Path.GetDirectoryName(Path.GetDirectoryName(headerPath))));
        text.Append("). Do not edit by hand.\n// </auto-generated>\n");
        text.Append("using System.Collections.Generic;\n\n#pragma warning disable IDE0130\n\nnamespace R3Config.Svc;\n\n");
        text.Append("public static partial class Win32ErrorSymbols\n{\n");
        text.Append("    private static partial IReadOnlyDictionary<int, string> BuildTable() => new Dictionary<int, string>\n    {\n");
        foreach (var (code, names) in symbols)
        {
            text.Append(CultureInfo.InvariantCulture, $"        [{code}] = \"{string.Join('|', names)}\",\n");
        }

        text.Append("    };\n}\n\n#pragma warning restore IDE0130\n");
        File.WriteAllText(outPath, text.ToString(), new UTF8Encoding(false));
        Console.WriteLine($"win32 symbols: {symbols.Count} codes, {symbols.Values.Sum(list => list.Count)} names");
    }
}
